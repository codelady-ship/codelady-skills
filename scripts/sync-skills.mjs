// Copies each skill's SKILL.md into src/server/prompts.generated.ts.
// The file is server-only: the prompts never reach the browser.
// Run: npm run sync-skills   (also runs before dev and build)
//
// Add a new skill: add one line to SOURCES, then create src/skills/<slug>.ts
// and register it in src/skills/registry.ts.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const repos = join(root, '..');
const userSkills = join(homedir(), '.claude', 'skills');

const SOURCES = {
  'scam-checker': join(repos, 'scholarship-visa-scam-checker', 'SKILL.md'),
  'study-abroad': join(repos, 'study-abroad-copilot', 'SKILL.md'),
  'travel': join(repos, 'student-travel-copilot', 'SKILL.md'),
  'job': join(repos, 'job-application-copilot', 'SKILL.md'),
  'voiceover': join(repos, 'azerbaijani-voiceover-studio', 'SKILL.md'),
  // MIT, from coreyhaines31/marketingskills (fork texnoera-jt334/marketingskills)
  'social-post': join(userSkills, 'social', 'SKILL.md'),
};

const out = {};
for (const [slug, file] of Object.entries(SOURCES)) {
  if (!existsSync(file)) { console.warn(`[sync-skills] missing ${file}, ${slug} skipped`); continue; }
  // Drop YAML frontmatter; the body is the instruction set.
  out[slug] = readFileSync(file, 'utf8').replace(/^---[\s\S]*?\n---\n/, '').trim();
}

const body = `// GENERATED by scripts/sync-skills.mjs. Do not edit by hand.\nimport 'server-only';\n\nexport const SKILL_PROMPTS: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync(join(root, 'src', 'server', 'prompts.generated.ts'), body);
console.log(`[sync-skills] ${Object.keys(out).length} skills: ${Object.keys(out).join(', ')}`);
